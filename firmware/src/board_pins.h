/* ============================================================================
 * board_pins.h —— 硬件接线约定
 *
 *  ┌──────────────┬───────────────┬─────────────────────────────────────────┐
 *  │ ESP8266 引脚 │ 方向          │ 接到哪里                                 │
 *  ├──────────────┼───────────────┼─────────────────────────────────────────┤
 *  │ GPIO1 (TX)   │ ESP → MCU     │ MCU 的 RX —— 下行：应答 / 事件            │
 *  │ GPIO3 (RX)   │ MCU → ESP     │ MCU 的 TX —— 上行：查询 / 命令            │
 *  │ GPIO2        │ ESP → 调试口  │ UART1-TX(仅发送) 115200，看日志           │
 *  │ RST          │ MCU → ESP     │ MCU GPIO 控制，低电平复位                 │
 *  │ EN / CH_PD   │ —             │ 10k 上拉到 3.3V                          │
 *  │ GPIO0        │ —             │ 10k 上拉到 3.3V（运行；下拉=烧录模式）     │
 *  │ GPIO15       │ —             │ 10k 下拉到 GND（必须）                    │
 *  │ GPIO16 (D0)  │ ESP → LED     │ 状态灯（可选，-1 = 不接）                 │
 *  │ GPIO14 (D5)  │ 按键 → ESP    │ 长按 3s 清凭据重新配网（可选，-1 = 不接）  │
 *  └──────────────┴───────────────┴─────────────────────────────────────────┘
 *
 *  两个必须知道的坑：
 *  1) ESP8266 只有 UART0 能同时收发，UART1 只有 TX。所以与 MCU 的协议走
 *     UART0(GPIO1/GPIO3)，也就是模块的下载口；调试日志只能从 UART1(GPIO2)
 *     单向往外吐。好处：可插拔模块拔下来 USB-TTL 接的还是同一对脚。
 *  2) 上电瞬间 UART0 会先吐 74880bps 的启动噪声，MCU 侧解析器必须能靠行首
 *     "+OK"/"-ERR"/"@EVT" 重新同步（host/esp_link.c 已实现）。
 * ==========================================================================*/

